#!/usr/bin/env node
/*
 * Builds src/assets/primeng-themes/taap.css from PrimeNG's saga-green theme by
 * swapping its hard-coded colors, font stack and radius for our design tokens
 * (src/styles/_tokens.scss). Re-run after upgrading PrimeNG:
 *
 *   node scripts/build-primeng-theme.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const source = path.join(root, 'src/assets/primeng-themes/saga-green.css');
const target = path.join(root, 'src/assets/primeng-themes/taap.css');

// Hex values in saga-green -> token. Anything not listed is left as PrimeNG ships it.
const colors = {
    // Primary: saga's green becomes our teal.
    '#4CAF50': 'var(--color-primary)',
    '#449E48': 'var(--color-primary-hover)',
    '#3D8C40': 'var(--color-primary-active)',
    '#B7E0B8': 'var(--color-primary-border)',
    '#E8F5E9': 'var(--color-primary-subtle)',
    '#A6D8A9': 'var(--teal-200)',
    '#8FCE94': 'var(--teal-300)',

    // Text, borders and surfaces.
    '#495057': 'var(--color-text)',
    '#212529': 'var(--color-text)',
    '#6C757D': 'var(--color-text-muted)',
    '#CED4DA': 'var(--color-border-strong)',
    '#DEE2E6': 'var(--color-border)',
    '#E9ECEF': 'var(--color-surface-hover)',
    '#F8F9FA': 'var(--color-surface-muted)',

    // Danger: invalid fields, danger buttons, error messages and toasts.
    '#F44336': 'var(--color-danger)',
    '#D32F2F': 'var(--red-600)',
    '#C02929': 'var(--red-700)',
    '#AA2424': 'var(--red-800)',
    '#EDACAC': 'var(--red-100)',
    '#FFCDD2': 'var(--color-danger-subtle)',
    '#E60017': 'var(--color-danger)',
    '#73000C': 'var(--red-800)',

    // Success, warning and info messages and toasts.
    '#C8E6C9': 'var(--color-success-subtle)',
    '#439446': 'var(--green-600)',
    '#224A23': 'var(--green-800)',
    '#FFECB3': 'var(--color-warning-subtle)',
    '#D9A300': 'var(--amber-500)',
    '#6D5100': 'var(--amber-800)',
    '#B3E5FC': 'var(--color-info-subtle)',
    '#0891CF': 'var(--teal-500)',
    '#044868': 'var(--teal-800)',
};

// rgba() tints of the colors above (hover backgrounds of text/outlined buttons).
const tints = [
    [/rgba\(76, 175, 80, /g, 'rgba(63, 125, 145, '],
    [/rgba\(211, 47, 47, /g, 'rgba(178, 58, 46, '],
];

// The tokens own these names, so the theme must not redefine them.
const ownedVariable = /^\s*--(teal|green|focus-ring)\b[^:]*:/;

const fontStack = /-apple-system, BlinkMacSystemFont, "?Segoe UI"?, Roboto, Helvetica, Arial, sans-serif, "?Apple Color Emoji"?, "?Segoe UI Emoji"?, "?Segoe UI Symbol"?/g;

const hexPattern = new RegExp(Object.keys(colors).join('|'), 'gi');

const output = fs.readFileSync(source, 'utf8')
    .split('\n')
    .filter(line => !ownedVariable.test(line))
    .map(line => {
        line = line.replace(hexPattern, hex => colors[hex.toUpperCase()]);
        for (const [pattern, replacement] of tints) {
            line = line.replace(pattern, replacement);
        }
        line = line.replace(fontStack, 'var(--font-sans)');
        if (/radius/.test(line)) {
            line = line.replace(/\b3px\b/g, 'var(--radius-sm)');
        }
        return line;
    })
    .join('\n');

const header = '/* Generated by scripts/build-primeng-theme.js from saga-green.css. Do not edit by hand. */\n';
fs.writeFileSync(target, header + output);
console.log(`Wrote ${path.relative(root, target)}`);
